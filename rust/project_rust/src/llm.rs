use crate::config::ProviderConfig;
use reqwest::blocking::Client;
use serde_json::{Value, json};
use std::{env, time::Duration};

#[derive(Debug, Clone)]
pub struct LlmRequest {
    pub model: String,
    pub system: String,
    pub prompt: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LlmResponse {
    pub text: String,
    pub input_tokens: u32,
    pub output_tokens: u32,
}

/// Extract files from a generator response using the stable format requested
/// in the agent prompt: `<file path="relative/path">...content...</file>`.
/// The path is intentionally left for FileSandbox to validate before writing.
pub fn extract_files(text: &str) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut rest = text;
    while let Some(start) = rest.find("<file ") {
        let after_start = &rest[start + 6..];
        let Some(path_start) = after_start.find("path=\"") else {
            break;
        };
        let path_value = &after_start[path_start + 6..];
        let Some(path_end) = path_value.find('"') else {
            break;
        };
        let path = path_value[..path_end].trim();
        let content_start = path_end + 1;
        let Some(content_open_end) = path_value[content_start..].find('>') else {
            break;
        };
        let content = &path_value[content_start + content_open_end + 1..];
        let Some(content_end) = content.find("</file>") else {
            break;
        };
        files.push((path.to_string(), content[..content_end].to_string()));
        rest = &content[content_end + 7..];
    }
    files
}

pub fn generate(provider: &ProviderConfig, request: &LlmRequest) -> Result<LlmResponse, String> {
    if provider.kind == "demo" {
        let text = if request
            .prompt
            .contains("Return every created or changed file")
        {
            format!(
                "Demo implementation for the requested task.\n<file path=\"demo_output.txt\">Generated by the offline provider.\n</file>"
            )
        } else {
            format!("Demo response for: {}", request.prompt)
        };
        return Ok(LlmResponse {
            text,
            input_tokens: request.prompt.split_whitespace().count() as u32,
            output_tokens: 4,
        });
    }
    let client = Client::builder()
        .timeout(Duration::from_secs(provider.timeout_secs))
        .build()
        .map_err(|error| error.to_string())?;
    match provider.kind.as_str() {
        "ollama" => ollama(&client, provider, request),
        "openai" => openai(&client, provider, request),
        "anthropic" => anthropic(&client, provider, request),
        other => Err(format!("unsupported LLM provider kind: {other}")),
    }
}

fn endpoint(base: &str, path: &str) -> String {
    format!("{}{}", base.trim_end_matches('/'), path)
}

fn key(provider: &ProviderConfig) -> Result<String, String> {
    if provider.api_key_env.is_empty() {
        return Err(format!(
            "provider {} has no api_key_env configured",
            provider.id
        ));
    }
    env::var(&provider.api_key_env)
        .map_err(|_| format!("environment variable {} is not set", provider.api_key_env))
}

fn checked_json(response: reqwest::blocking::Response) -> Result<Value, String> {
    let status = response.status();
    let body = response.text().map_err(|error| error.to_string())?;
    if !status.is_success() {
        return Err(format!("LLM HTTP {}: {}", status.as_u16(), body));
    }
    serde_json::from_str(&body).map_err(|error| format!("invalid LLM response: {error}"))
}

fn ollama(
    client: &Client,
    provider: &ProviderConfig,
    request: &LlmRequest,
) -> Result<LlmResponse, String> {
    let value = checked_json(
        client
            .post(endpoint(&provider.base_url, "/api/generate"))
            .json(&json!({"model": request.model, "system": request.system, "prompt": request.prompt, "stream": false}))
            .send()
            .map_err(|error| error.to_string())?,
    )?;
    parse_ollama(&value)
}

fn parse_ollama(value: &Value) -> Result<LlmResponse, String> {
    let text = value["response"]
        .as_str()
        .ok_or_else(|| "Ollama response is missing the response field".to_string())?;
    Ok(LlmResponse {
        text: text.to_string(),
        input_tokens: value["prompt_eval_count"].as_u64().unwrap_or(0) as u32,
        output_tokens: value["eval_count"].as_u64().unwrap_or(0) as u32,
    })
}

fn openai(
    client: &Client,
    provider: &ProviderConfig,
    request: &LlmRequest,
) -> Result<LlmResponse, String> {
    let value = checked_json(
        client
            .post(endpoint(&provider.base_url, "/v1/chat/completions"))
            .bearer_auth(key(provider)?)
            .json(&json!({"model": request.model, "messages": [{"role": "system", "content": request.system}, {"role": "user", "content": request.prompt}]}))
            .send()
            .map_err(|error| error.to_string())?,
    )?;
    Ok(LlmResponse {
        text: value["choices"][0]["message"]["content"]
            .as_str()
            .unwrap_or_default()
            .to_string(),
        input_tokens: value["usage"]["prompt_tokens"].as_u64().unwrap_or(0) as u32,
        output_tokens: value["usage"]["completion_tokens"].as_u64().unwrap_or(0) as u32,
    })
}

fn anthropic(
    client: &Client,
    provider: &ProviderConfig,
    request: &LlmRequest,
) -> Result<LlmResponse, String> {
    let value = checked_json(
        client
            .post(endpoint(&provider.base_url, "/v1/messages"))
            .header("x-api-key", key(provider)?)
            .header("anthropic-version", "2023-06-01")
            .json(&json!({"model": request.model, "max_tokens": 2048, "system": request.system, "messages": [{"role": "user", "content": request.prompt}]}))
            .send()
            .map_err(|error| error.to_string())?,
    )?;
    Ok(LlmResponse {
        text: value["content"][0]["text"]
            .as_str()
            .unwrap_or_default()
            .to_string(),
        input_tokens: value["usage"]["input_tokens"].as_u64().unwrap_or(0) as u32,
        output_tokens: value["usage"]["output_tokens"].as_u64().unwrap_or(0) as u32,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{
        io::{Read, Write},
        net::TcpListener,
        thread,
    };

    fn provider(kind: &str, base_url: String) -> ProviderConfig {
        ProviderConfig {
            id: kind.into(),
            kind: kind.into(),
            base_url,
            api_key_env: String::new(),
            timeout_secs: 2,
        }
    }

    fn request() -> LlmRequest {
        LlmRequest {
            model: "test-model".into(),
            system: "Be concise".into(),
            prompt: "Hello model".into(),
        }
    }

    #[test]
    fn demo_provider_is_deterministic_and_offline() {
        let response = generate(&provider("demo", "demo://local".into()), &request()).unwrap();
        assert!(response.text.contains("Hello model"));
        assert_eq!(response.input_tokens, 2);
    }

    #[test]
    fn extracts_structured_files_from_generator_response() {
        let response = r#"Here is the implementation:
<file path="src/main.py">
print("hello")
</file>
<file path="README.md"># Demo</file>"#;
        assert_eq!(
            extract_files(response),
            vec![
                ("src/main.py".into(), "\nprint(\"hello\")\n".into()),
                ("README.md".into(), "# Demo".into()),
            ]
        );
    }

    #[test]
    fn malformed_file_blocks_are_ignored() {
        assert!(extract_files("<file path=\"broken.py\">missing close").is_empty());
    }

    #[test]
    fn ollama_response_parser_reads_text_and_tokens() {
        let response = parse_ollama(
            &json!({"response":"Generated answer","prompt_eval_count":7,"eval_count":3}),
        )
        .unwrap();
        assert_eq!(response.text, "Generated answer");
        assert_eq!((response.input_tokens, response.output_tokens), (7, 3));
    }

    #[test]
    #[ignore = "requires permission to bind a loopback TCP socket"]
    fn ollama_provider_sends_real_http_request() {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let address = listener.local_addr().unwrap();
        let server = thread::spawn(move || {
            let (mut stream, _) = listener.accept().unwrap();
            let mut bytes = [0; 4096];
            let read = stream.read(&mut bytes).unwrap();
            let request = String::from_utf8_lossy(&bytes[..read]);
            assert!(request.starts_with("POST /api/generate"));
            let body = r#"{"response":"Generated answer","prompt_eval_count":7,"eval_count":3}"#;
            write!(stream, "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{}", body.len(), body).unwrap();
        });
        let response =
            generate(&provider("ollama", format!("http://{address}")), &request()).unwrap();
        server.join().unwrap();
        assert_eq!(response.text, "Generated answer");
        assert_eq!((response.input_tokens, response.output_tokens), (7, 3));
    }

    #[test]
    fn unsupported_provider_has_actionable_error() {
        let error =
            generate(&provider("unknown", "http://localhost".into()), &request()).unwrap_err();
        assert!(error.contains("unsupported LLM provider"));
    }
}
