# Lokální shlukovací koeficient každého vrcholu
clustering_coefficients = {}

for vertex in vertices:
    neighbors = sorted(set(adjacency_list[vertex]))
    k = len(neighbors)
    links_between_neighbors = 0

    for i in range(k):
        for j in range(i + 1, k):
            if neighbors[j] in adjacency_list[neighbors[i]]:
                links_between_neighbors += 1

    if k < 2:
        clustering_coefficients[vertex] = 0.0
    else:
        clustering_coefficients[vertex] = 2 * links_between_neighbors / (k * (k - 1))

clustering_results = pd.DataFrame({
    "ID": vertices,
    "ClusteringCoefficient": [clustering_coefficients[v] for v in vertices]
})
