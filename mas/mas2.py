import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
filename = "KarateClub.csv"

df = pd.read_csv(filename)

print(df.head())
print()
print(df.shape)
print()
print(df.columns)

df = pd.read_csv(filename, sep=';', header=None)

print(df.head())
print()
print(len(df))

edges = []

for i in range(len(df)):
    vertex1 = int(df.iloc[i, 0])
    vertex2 = int(df.iloc[i, 1])
    edges.append((vertex1, vertex2))

print("hrany:", len(edges))

vertices = set()

for vertex1, vertex2 in edges:
    vertices.add(vertex1)
    vertices.add(vertex2)

vertices = sorted(vertices)
print("vrcholy:", len(vertices))

n = len(vertices)
adjacency_matrix = np.zeros((n, n), dtype=int)
print(adjacency_matrix.shape)

for vertex1, vertex2 in edges:
    adjacency_matrix[vertex1 - 1][vertex2 - 1] = 1
    adjacency_matrix[vertex2 - 1][vertex1 - 1] = 1

adjacency_list = {}

for vertex in vertices:
    adjacency_list[vertex] = []
for vertex1, vertex2 in edges:
    adjacency_list[vertex1].append(vertex2)
    adjacency_list[vertex2].append(vertex1)

for vertex in vertices:
    print(vertex, ":", adjacency_list[vertex])

degrees = {}

for vertex in vertices:
    degrees[vertex] = len(adjacency_list[vertex])
for vertex in vertices:
    print("Vrchol", vertex, "stupen =", degrees[vertex])

degree_values = list(degrees.values())
print("Degree values :",  degree_values)

print("Minimum degree:", min(degree_values))
print("Maximum degree:",  max(degree_values))
print("Average degree:", sum(degree_values) / len(degree_values))

degree_frequency = {}

for degree in degree_values:
    if degree not in degree_frequency:
        degree_frequency[degree] = 0

    degree_frequency[degree] += 1

degree_frequency = dict(sorted(degree_frequency.items()))

print("Stupen | Frequency")

for degree, frequency in degree_frequency.items():
    print(degree, "|", frequency)

degree_relative_frequency = {}

for degree, frequency in degree_frequency.items():
    degree_relative_frequency[degree] = frequency / len(vertices)

results = pd.DataFrame({
    "Degree": degree_frequency.keys(),
    "Frequency": degree_frequency.values(),
    "Relative frequency": degree_relative_frequency.values()
})
results["Relative frequency (%)"] = results["Relative frequency"] * 100

display(results)

plt.figure(figsize=(10, 6))

plt.bar(
    degree_frequency.keys(),
    degree_frequency.values()
)

plt.xlabel("stupeň")
plt.ylabel("počet vrcholů")
plt.title("počet vrcholů s daným stupněm ")

plt.xticks(list(degree_frequency.keys()))

plt.show()