def create_knn_graph(X, k=3, sigma=1):

    n = len(X)
    gamma = 1 / (2 * sigma**2)

    similarity = rbf_kernel(X, gamma=gamma)

    np.fill_diagonal(similarity, -np.inf)

    G = nx.Graph()
    G.add_nodes_from(range(n))

    for i in range(n):

        neighbors = np.argsort(
            -similarity[i], kind="stable"
        )[:k]

        for j in neighbors:
            j = int(j)

            G.add_edge(
                i, j,
                weight=float(similarity[i, j])
            )

    for i in range(n):
        G.nodes[i]["Species"] = str(
            df.iloc[i]["Species"]
        )

    return G

