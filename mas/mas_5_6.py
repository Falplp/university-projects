k_values = [3, 5, 10]

graphs = {}
results = []

for k in k_values:

    G = create_knn_graph(X, k=k, sigma=1)

    graphs[k] = G

    results.append({
        "k": k,
        "Sigma": 1,
        "Nodes": G.number_of_nodes(),
        "Edges": G.number_of_edges(),
        "Average_Degree": 2 * G.number_of_edges() / G.number_of_nodes(),
        "Density": nx.density(G),
        "Clustering": nx.average_clustering(G),
        "Components": nx.number_connected_components(G)
    })

results_df = pd.DataFrame(results)

display(results_df)

community_results = []

for k, G in graphs.items():

    communities = nx_comm.louvain_communities(
        G,
        weight="weight",
        seed=4
    )

    modularity = nx_comm.modularity(
        G, communities, weight="weight"
    )

    community_results.append({
        "k": k,
        "Pocet_komunit": len(communities),
        "Modularita": modularity
    })

display(pd.DataFrame(community_results))

